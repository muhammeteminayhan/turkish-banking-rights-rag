"""Per-document parse statistics and problems: data/processed/parse_report.{json,md}."""

from collections import Counter
from collections.abc import Sequence

from pydantic import BaseModel, ConfigDict

from finhak.ingest.sources import Origin
from finhak.parsing.chunker import Chunk

_FROZEN = ConfigDict(frozen=True, extra="forbid")


class DocReport(BaseModel):
    model_config = _FROZEN

    doc_id: str
    origin: Origin
    maddeler: dict[str, int]
    fikralar: int
    fikralar_inferred: int
    mulga_maddeler: int
    mulga_fikralar: int
    chunks: dict[str, int]
    oversized_chunks: tuple[str, ...]
    unresolved_refs: tuple[str, ...]
    ambiguous_refs: tuple[str, ...]
    unplaced: tuple[str, ...]
    warnings: tuple[str, ...]
    annexes: int
    pdf_madde_headings: int | None
    page_coverage: float | None
    notes: tuple[str, ...]
    unreferenced_notes: tuple[str, ...] = ()  # footnotes/endnotes no chunk cites


class ParseReport(BaseModel):
    model_config = _FROZEN

    documents: tuple[DocReport, ...]


def chunk_stats(
    chunks: Sequence[Chunk], max_chars: int
) -> tuple[dict[str, int], tuple[str, ...], tuple[str, ...], tuple[str, ...]]:
    units = {str(unit): count for unit, count in Counter(c.unit for c in chunks).items()}
    oversized = tuple(chunk.id for chunk in chunks if len(chunk.text) > max_chars)
    unresolved = tuple(c.id for c in chunks if any("[kaynakta bulunamadı]" in n for n in c.notes))
    ambiguous = tuple(c.id for c in chunks if any("[belirsiz:" in n for n in c.notes))
    return units, oversized, unresolved, ambiguous


def page_coverage(chunks: Sequence[Chunk]) -> float | None:
    if not chunks:
        return None
    return round(sum(1 for chunk in chunks if chunk.pages) / len(chunks), 3)


def render_markdown(report: ParseReport) -> str:
    lines = [
        "# Parse report",
        "",
        "Generated by `scripts/parse_sources.py`. `inferred` fıkra numbers were counted from",
        "paragraphs because the text does not print them (older laws).",
        "",
        "| Document | Madde (madde/geçici/ek) | PDF headings | Fıkra (inferred) | Mülga m/f "
        "| Chunks | Pages found | Unresolved / ambiguous refs | Unplaced | Warnings |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for doc in report.documents:
        counts = "/".join(str(doc.maddeler.get(kind, 0)) for kind in ("madde", "gecici", "ek"))
        total = sum(doc.maddeler.values())
        pdf = "–" if doc.pdf_madde_headings is None else str(doc.pdf_madde_headings)
        match = "" if doc.pdf_madde_headings in (None, total) else " ⚠"
        pages = "–" if doc.page_coverage is None else f"{doc.page_coverage:.0%}"
        lines.append(
            f"| `{doc.doc_id}` | {counts} | {pdf}{match} "
            f"| {doc.fikralar} ({doc.fikralar_inferred}) "
            f"| {doc.mulga_maddeler}/{doc.mulga_fikralar} | {sum(doc.chunks.values())} | {pages} "
            f"| {len(doc.unresolved_refs)} / {len(doc.ambiguous_refs)} | {len(doc.unplaced)} "
            f"| {len(doc.warnings)} |"
        )
    details = [doc for doc in report.documents if _has_details(doc)]
    if details:
        lines += ["", "## Details", ""]
    for doc in details:
        lines.append(f"### `{doc.doc_id}`")
        for label, values in (
            ("Notes", doc.notes),
            ("Warnings", doc.warnings),
            ("Unplaced text", doc.unplaced),
            ("Unresolved references in", doc.unresolved_refs),
            ("Ambiguous references in", doc.ambiguous_refs),
            ("Chunks over the size limit", doc.oversized_chunks),
            ("Footnotes/endnotes no chunk cites", doc.unreferenced_notes),
        ):
            if values:
                lines.append(
                    f"- {label}: " + "; ".join(f"`{v}`" if " " not in v else v for v in values)
                )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _has_details(doc: DocReport) -> bool:
    return any(
        (
            doc.notes,
            doc.warnings,
            doc.unplaced,
            doc.unresolved_refs,
            doc.ambiguous_refs,
            doc.oversized_chunks,
            doc.unreferenced_notes,
        )
    )
